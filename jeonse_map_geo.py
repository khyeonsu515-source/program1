df = pd.read_csv("jeonse_data.csv", encoding="utf-8-sig")
df.columns = ["주택유형","광역","권역","시군구","읍면동"] + list(df.columns[5:])
MONTHS = [c for c in df.columns if c.startswith("202")]
df[MONTHS] = df[MONTHS].replace("-", np.nan).astype(float)
LATEST = MONTHS[-1]

# 광역 평균
metro = df[
    (df["주택유형"] == "아파트") &
    (df["권역"] == "소계") & (df["시군구"] == "소계") & (df["읍면동"] == "소계") &
    (~df["광역"].isin(["전국","수도권","지방","5대광역시","6대광역시","8개도","9개도"]))
].set_index("광역")[LATEST].to_dict()

# 컬러맵 (45 → 90%: 초록 → 노랑 → 빨강)
CMAP = mcolors.LinearSegmentedColormap.from_list("jr", [
    (0.0,  "#1b5e20"), (0.35, "#66bb6a"),
    (0.58, "#fdd835"), (0.75, "#f57c00"),
    (0.88, "#c62828"), (1.0,  "#7f0000"),
])
VMIN, VMAX = 45.0, 90.0

def ratio_to_color(v):
    if pd.isna(v):
        return "#cccccc"
    return CMAP((v - VMIN) / (VMAX - VMIN))

def risk_grade(v):
    if pd.isna(v):   return "데이터없음"
    if v >= 80:      return "위험"
    if v >= 70:      return "경계"
    if v >= 60:      return "주의"
    return "안전"

# 시군구 마커 수집
def get_markers():
    rows = []
    for _, r in df[df["주택유형"] == "아파트"].iterrows():
        prov, kwon, sgg, emd = r["광역"], r["권역"], r["시군구"], r["읍면동"]
        val = r[LATEST]
        if pd.isna(val) or prov in ("전국","수도권","지방","5대광역시","6대광역시","8개도","9개도"):
            continue
        pdict = CITY_COORD.get(prov, {})
        coord = None
        label = ""
        # 서울: 읍면동=구이름
        if prov == "서울" and emd != "소계":
            coord = pdict.get(emd); label = f"{prov} {emd}"
        # 경기: 시군구=도시/구
        elif prov == "경기" and sgg != "소계" and emd == "소계":
            coord = pdict.get(sgg); label = f"{prov} {sgg}"
        # 부산: 시군구=구
        elif prov == "부산" and sgg != "소계" and emd == "소계":
            coord = pdict.get(sgg); label = f"{prov} {sgg}"
        # 대구·인천·광주·대전·울산: 권역=구
        elif prov in ("대구","인천","광주","대전","울산") and kwon != "소계" and sgg == "소계" and emd == "소계":
            coord = pdict.get(kwon); label = f"{prov} {kwon}"
        # 경남 시군구
        elif prov == "경남" and sgg != "소계" and emd == "소계":
            coord = pdict.get(sgg); label = f"{prov} {sgg}"
        # 충북 청주 하위구
        elif prov == "충북" and kwon == "청주" and sgg != "소계" and emd == "소계":
            coord = pdict.get(sgg); label = f"청주 {sgg}"
        # 기타도: 권역=도시
        elif prov not in ("서울","경기","부산","대구","인천","광주","대전","울산") \
                and kwon != "소계" and sgg == "소계" and emd == "소계":
            coord = pdict.get(kwon); label = f"{prov} {kwon}"
        if coord:
            rows.append({"lon":coord[0],"lat":coord[1],"val":val,
                         "label":label,"grade":risk_grade(val)})
    return rows

markers = get_markers()
